import re, json, os
OUT = os.path.expanduser("~/workspace/whatsapp-groups-site/scraped/team229-indonesia.json")
seen, out, skipped = set(), [], []
for name, code, cat, desc in b.G:
    code = code.split("?")[0].strip()
    if not re.fullmatch(r"[A-Za-z0-9_-]+", code) or len(code) < 8:
        skipped.append((name, code)); continue
    if code.lower() in seen:
        skipped.append((name, code)); continue
    seen.add(code.lower())
    e = {"name": name, "invite": f"https://chat.whatsapp.com/{code}", "cat": cat, "country": "Indonesia"}
    if desc: e["desc"] = desc
    out.append(e)
with open(OUT, "w", encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=1)
print("saved:", len(out), "| skipped:", len(skipped))
